# 题目解析：找距离 n 最近的斐波那契数，求最小步数一、题意梳理
# 斐波那契定义：
#
# \(f_i=
# \begin{cases}
# 0 & i=0 \\
# 1 & i=1 \\
# f_{i-2}+f_{i-1} & i\ge2
# \end{cases}\)
# 数列：0,1,1,2,3,5,8,13,21,...
# 2. 操作规则：每次 ±1，求把 n 变成斐波那契数最少需要几步。
# 3. 样例：输入 15，前后斐波那契数是 13、21
n=int(input())
a=0
b=1
c=1
# 循环直到b>n
while(c<n):
    a=b
    b=c
    c=a+b
print(min(n-b,c-n))